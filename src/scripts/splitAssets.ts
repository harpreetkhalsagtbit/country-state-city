/**
 * Generates the per-country files used by `country-state-city/lib/lazy` and `lib/lazy-geo`
 * from the three combined assets (country.json, state.json, city.json). Runs before `tsc`.
 *
 * Output (all gitignored, rebuilt on every build):
 *   src/assets/lite/country.json      [[isoCode, name], ...]
 *   src/assets/states/{CC}.json       [[isoCode, name], ...] sorted by name
 *   src/assets/cities/{CC}.json       [[stateCode, [name, ...]], ...]
 *   src/assets/cities-geo/{CC}.json   [[stateCode, [[name, latitude, longitude], ...]], ...]
 *   src/generated/loaders.ts          one static import() per file, so bundlers can split them
 *   src/generated/geoLoaders.ts
 *
 * States inside a city file keep their order from city.json, and cities inside a state are
 * sorted by name, so the lazy API returns rows in the same order as City.getCitiesOf*.
 */
import fs from 'fs';
import path from 'path';

type Row = string[];

const root = process.cwd();
const assets = path.join(root, 'src/assets');
const generated = path.join(root, 'src/generated');
const OUTPUT_DIRS = ['lite', 'states', 'cities', 'cities-geo'];

const readJSON = (file: string) => {
	return JSON.parse(fs.readFileSync(path.join(assets, file), 'utf-8'));
};
const writeJSON = (file: string, data: unknown) => {
	const target = path.join(assets, file);
	fs.mkdirSync(path.dirname(target), { recursive: true });
	fs.writeFileSync(target, JSON.stringify(data));
};
// Same ordering as utils.compare, which the existing API uses.
const byString = (a: string, b: string) => {
	if (a < b) return -1;
	if (a > b) return 1;
	return 0;
};
// eslint-disable-next-line no-unused-vars
const groupBy = <T>(items: T[], keyOf: (item: T) => string): Map<string, T[]> => {
	const groups = new Map<string, T[]>();
	items.forEach((item) => {
		const key = keyOf(item);
		if (!groups.has(key)) groups.set(key, []);
		(groups.get(key) as T[]).push(item);
	});
	return groups;
};

const countries: { name: string; isoCode: string }[] = readJSON('country.json');
const states: { name: string; isoCode: string; countryCode: string }[] = readJSON('state.json');
const cities: Row[] = readJSON('city.json'); // [name, countryCode, stateCode, latitude, longitude]

OUTPUT_DIRS.forEach((dir) => {
	fs.rmSync(path.join(assets, dir), { recursive: true, force: true });
});

writeJSON(
	'lite/country.json',
	countries.map((c) => {
		return [c.isoCode, c.name];
	}),
);

const statesByCountry = groupBy(states, (s) => {
	return s.countryCode;
});
statesByCountry.forEach((list, countryCode) => {
	const rows = list.map((s) => {
		return [s.isoCode, s.name];
	});
	rows.sort((a, b) => {
		return byString(a[1], b[1]);
	});
	writeJSON(`states/${countryCode}.json`, rows);
});

const citiesByCountry = groupBy(cities, (c) => {
	return c[1];
});
citiesByCountry.forEach((list, countryCode) => {
	const byState = Array.from(
		groupBy(list, (c) => {
			return c[2];
		}),
	);
	byState.forEach(([, stateCities]) => {
		stateCities.sort((a, b) => {
			return byString(a[0], b[0]);
		});
	});
	writeJSON(
		`cities/${countryCode}.json`,
		byState.map(([stateCode, stateCities]) => {
			return [
				stateCode,
				stateCities.map((c) => {
					return c[0];
				}),
			];
		}),
	);
	writeJSON(
		`cities-geo/${countryCode}.json`,
		byState.map(([stateCode, stateCities]) => {
			return [
				stateCode,
				stateCities.map((c) => {
					return [c[0], c[3], c[4]];
				}),
			];
		}),
	);
});

const loaderMap = (name: string, dir: string, codes: string[]) => {
	const lines = codes
		.slice()
		.sort()
		.map((code) => {
			return `\t${code}: () => import('../assets/${dir}/${code}.json'),`;
		});
	return `export const ${name}: Loaders = {\n${lines.join('\n')}\n};\n`;
};
const header = [
	'/* AUTO-GENERATED by src/scripts/splitAssets.ts - do not edit. */',
	'/* eslint-disable */',
	"import { Loaders } from '../lazyLoader';",
	'',
].join('\n');

fs.mkdirSync(generated, { recursive: true });
fs.writeFileSync(
	path.join(generated, 'loaders.ts'),
	`${header}\n${loaderMap('stateLoaders', 'states', Array.from(statesByCountry.keys()))}\n${loaderMap(
		'cityLoaders',
		'cities',
		Array.from(citiesByCountry.keys()),
	)}`,
);
fs.writeFileSync(
	path.join(generated, 'geoLoaders.ts'),
	`${header}\n${loaderMap('cityGeoLoaders', 'cities-geo', Array.from(citiesByCountry.keys()))}`,
);

console.log(
	`splitAssets: ${countries.length} countries, ${statesByCountry.size} state files, ${citiesByCountry.size} city files`,
);
